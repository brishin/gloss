import type { FileChange, FileJudgment, GroupDefinition, Visual } from '@gloss/protocol';
import type { JudgeAnswer, JudgeQuestion } from '../adapters/types.ts';
import { hashOf } from '../hash.ts';

/**
 * Jev question wording and thresholds, ported verbatim from the pulls.review evals
 * (pulls.review-evals/typesafe-2026-10-26-round3/src/questions.ts, state.ts). Criteria
 * describe general boundaries only. Retuning changes `QUESTIONS_VERSION`, which is in
 * every judge cache key.
 */
export const YES = 0.7;
export const NO = 0.3;

/** Per-file yes/no questions that need no groups, so they start the moment the diff is in. */
export const FILE_QUESTIONS: Record<string, JudgeQuestion> = {
  auth_check: {
    type: 'bool',
    instructions: 'Does the diff in `file.diff` change an authentication, authorization or permission check?',
    criteria: {
      true: 'The diff adds, removes or changes code that decides who may sign in, call an endpoint, or see or change data: for example an auth dependency on a route, a list of allowed clients, a role or permission check, or token validation.',
      false:
        'The diff only tests or calls existing auth code without changing what it allows, or does not involve authentication or authorization at all.',
    },
  },
  stored_data: {
    type: 'bool',
    instructions: 'Does the diff in `file.diff` delete, rename or migrate a database schema or stored records?',
    criteria: {
      true: 'A database migration, a change to table or column definitions such as ORM models, or code that deletes or rewrites records already stored.',
      false:
        'Changes to API request or response shapes, generated API clients, caches or in-memory state, with the stored database left as it is.',
    },
  },
  secrets_signing: {
    type: 'bool',
    instructions:
      'Does the diff in `file.diff` change how secrets, credentials, API keys, or signing keys and certificates are stored, read or used?',
  },
  personal_data: {
    type: 'bool',
    instructions:
      'Does the diff in `file.diff` change what personal data about users is collected, stored, logged or sent to third parties?',
  },
  exported_signature: {
    type: 'bool',
    instructions: 'Does the diff in `file.diff` change the signature of an exported function, type or endpoint?',
  },
  tests_only: { type: 'bool', instructions: 'Is `file` only tests, fixtures or stories?' },
  generated: { type: 'bool', instructions: 'Is `file` generated by a tool rather than written by hand?' },
};

/** Which group a file belongs to, plus the null case; asked once the LLM has defined groups. */
export function groupQuestions(groups: readonly GroupDefinition[]): Record<string, JudgeQuestion> {
  const criteria = Object.fromEntries(groups.map((group) => [group.key, `${group.label}: ${group.summary}`]));
  return {
    group: { type: 'choice', instructions: 'Which review group is the change in `file` part of?', criteria },
    fits_any_group: {
      type: 'bool',
      instructions: {
        question: 'Does the change in `file` fit any of these review groups?',
        review_groups: criteria,
      },
    },
  };
}

/**
 * Which candidate picture to show, if any. The model proposes 2-3; Jev ranks them with
 * `best` and filters each with `cN_explains`, so a tour never shows a picture that
 * misleads. With pictures, Jev sees each rendered as `<image-N>` beside its spec.
 */
export function visualQuestions(count: number, withImages: boolean): Record<string, JudgeQuestion> {
  const ids = Array.from({ length: count }, (_, i) => `c${i + 1}`);
  const picture = (id: string, i: number) =>
    withImages ? `picture <image-${i + 1}> (\`candidates.${id}\`)` : `\`candidates.${id}\``;
  const explains = Object.fromEntries(
    ids.map((id, i) => [
      `${id}_explains`,
      {
        type: 'bool',
        instructions: `Does ${picture(id, i)} show the main decision of the change in \`summary\` accurately, and can a reviewer read it at a glance?`,
        criteria: {
          true: 'It matches what the change does, draws a choice the change makes rather than a file list or call graph, and its labels and layout are legible.',
          false:
            'It contradicts or overstates the change, only restates the file list, or is cluttered, cut off or hard to follow.',
        },
      } satisfies JudgeQuestion,
    ]),
  );
  if (count < 2) {
    return explains;
  }
  return {
    best: {
      type: 'choice',
      instructions: `Which candidate in \`candidates\` best explains the main decision in \`summary\` to a reviewer who has not seen the change?${withImages ? ' Each one is drawn in the picture its `picture` field names.' : ''}`,
      criteria: Object.fromEntries(ids.map((id) => [id, `The ${id} picture.`])),
    },
    ...explains,
  };
}

export const QUESTIONS_VERSION = hashOf({
  FILE_QUESTIONS,
  group: groupQuestions([]),
  visual: [visualQuestions(2, true), visualQuestions(2, false)],
  YES,
  NO,
}).slice(0, 12);

/** ~12k tokens; keeps state + questions well under Jev's per-question context. */
export const DIFF_CHAR_CAP = 40_000;

/** Whole hunks in order until the cap; the rest are listed by header so Jev still sees where they are. */
export function truncatedDiff(file: FileChange): string {
  if (file.isBinary) {
    return '(binary file, no diff shown)';
  }
  if (file.truncated) {
    return '(diff too large, omitted)';
  }
  // Unlike the LLM prompt, a generated-looking file still sends its diff:
  // omitting it would hand the "generated" question its answer.
  const parts: string[] = [];
  let used = 0;
  let i = 0;
  for (; i < file.hunks.length; i++) {
    const text = `${file.hunks[i]!.header}\n${file.hunks[i]!.patch}`;
    if (used + text.length > DIFF_CHAR_CAP) {
      if (i === 0) {
        const cut = text.slice(0, DIFF_CHAR_CAP);
        parts.push(`${cut.slice(0, cut.lastIndexOf('\n'))}\n... (rest of this hunk omitted)`);
        i = 1;
      }
      break;
    }
    parts.push(text);
    used += text.length;
  }
  const rest = file.hunks.slice(i);
  if (rest.length) {
    parts.push(
      `... (${rest.length} more hunks omitted; their headers:)\n${rest.map((hunk) => hunk.header).join('\n')}`,
    );
  }
  return parts.join('\n');
}

export function fileState(prTitle: string, file: FileChange): Record<string, unknown> {
  return {
    pr_title: prTitle,
    file: {
      path: file.path,
      ...(file.previousPath ? { renamed_from: file.previousPath } : {}),
      status: file.status,
      lines_added: file.additions,
      lines_removed: file.deletions,
      diff: truncatedDiff(file),
    },
  };
}

const bool = (answer: JudgeAnswer | undefined) => (answer?.type === 'bool' ? answer.probability : undefined);

export function judgmentFromFileAnswers(answers: Record<string, JudgeAnswer>): FileJudgment {
  return {
    authCheck: bool(answers.auth_check),
    storedData: bool(answers.stored_data),
    secretsSigning: bool(answers.secrets_signing),
    personalData: bool(answers.personal_data),
    exportedSignature: bool(answers.exported_signature),
    testsOnly: bool(answers.tests_only),
    generated: bool(answers.generated),
  };
}

export function judgmentFromGroupAnswers(answers: Record<string, JudgeAnswer>): FileJudgment {
  const group = answers.group;
  return {
    group:
      group?.type === 'choice'
        ? { choice: group.choice, confidence: group.confidence, probabilities: group.probabilities }
        : undefined,
    fitsAnyGroup: bool(answers.fits_any_group),
  };
}

/** Without pictures, Jev reads each candidate's spec instead. */
export function visualState(
  prTitle: string,
  summary: string,
  decisions: readonly { text: string }[],
  candidates: readonly Visual[],
  withImages: boolean,
): Record<string, unknown> {
  return {
    pr_title: prTitle,
    summary,
    decisions: decisions.map((decision) => decision.text),
    candidates: Object.fromEntries(
      candidates.map((visual, i) => [
        `c${i + 1}`,
        { ...(withImages ? { picture: `<image-${i + 1}>` } : {}), ...visual },
      ]),
    ),
  };
}

/** Least sure a picture explains the change before it is shown. */
export const EXPLAINS = 0.5;

/**
 * Candidates ranked by `best` (model order breaks ties and stands in when there is one),
 * then the first that Jev thinks explains the change. `undefined` hides the visual.
 */
export function pickVisual(count: number, answers: Record<string, JudgeAnswer>): number | undefined {
  const best = answers.best;
  const weight = (i: number) => (best?.type === 'choice' ? (best.probabilities[`c${i + 1}`] ?? 0) : 0);
  const order = Array.from({ length: count }, (_, i) => i).sort((a, b) => weight(b) - weight(a) || a - b);
  return order.find((i) => (bool(answers[`c${i + 1}_explains`]) ?? 0) >= EXPLAINS);
}
